export function getSampleProposalDetail(id?: string): ProposalDetailMockData {
  if (!id) return defaultProposalDetail;
  const found = sampleProposals.find((p) => p.id === id || p.code === id);
  if (!found) return { ...defaultProposalDetail, id, code: id };
  return {
    ...defaultProposalDetail,
    id: found.id,
    code: found.code,
    generalInfo: {
      ...defaultProposalDetail.generalInfo,
      proposalNumber: found.code,
      proposalDate: found.createdAt,
      goodsCategory: found.category,
      goodsName: found.title,
    },
    items: [
      {
        id: "item-1",
        stt: 1,
        name: found.title.length > 30 ? found.title.slice(0, 30) : found.title,
        description: `${found.title} phục vụ công tác nghiệp vụ đơn vị.`,
        supplier: found.supplier,
        unit: "Bộ",
        quantity: 1,
        unitPrice: found.amount,
        vatPercent: 8,
        totalPrice: found.amount,
      },
    ],
    totals: {
      preTaxTotal: found.amount,
      vatTotal: Math.round(found.amount * 0.08),
      grandTotal: Math.round(found.amount * 1.08),
      amountInWords: defaultProposalDetail.totals.amountInWords,
    },
  };
}
